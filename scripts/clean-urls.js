// One-off migration: switch the site from ".html" URLs to clean URLs.
// Rewrites canonicals, og:url, JSON-LD, internal links, sitemap.xml and llms.txt,
// and generates _redirects with a 301 from every .html URL to its clean form.
// Usage: node scripts/clean-urls.js          (writes changes)
//        node scripts/clean-urls.js --check  (reports remaining .html URLs only)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const CHECK = process.argv.includes('--check');
const SITE = 'https://www.moroccoboutiquetours.com';
const pages = fs.readdirSync(root).filter(f => f.endsWith('.html')).sort();
const slugs = new Set(pages.map(f => f.slice(0, -5)));

const clean = slug => (slug === 'index' ? '/' : '/' + slug);

// Absolute URLs: https://www.moroccoboutiquetours.com/<slug>.html
const absRe = /https:\/\/(?:www\.)?moroccoboutiquetours\.com\/([a-z0-9-]+)\.html/g;
// Relative or root-relative hrefs/actions: href="tours.html", href="/tours.html#x"
const relRe = /\b(href|action)="\/?([a-z0-9-]+)\.html([#?][^"]*)?"/g;

let report = [];
function convert(text, file) {
  let n = 0;
  text = text.replace(absRe, (m, slug) => {
    if (!slugs.has(slug)) { report.push(`${file}: unknown page ${m}`); return m; }
    n++; return SITE + clean(slug);
  });
  text = text.replace(relRe, (m, attr, slug, rest) => {
    if (!slugs.has(slug)) { report.push(`${file}: unknown page ${m}`); return m; }
    n++; return `${attr}="${clean(slug)}${rest || ''}"`;
  });
  return { text, n };
}

const targets = [...pages, 'sitemap.xml', 'llms.txt'];
let total = 0;
for (const f of targets) {
  const p = path.join(root, f);
  if (!fs.existsSync(p)) continue;
  const before = fs.readFileSync(p, 'utf8');
  const { text, n } = convert(before, f);
  if (CHECK) { if (n) console.log(`${f}: ${n} .html URLs remain`); total += n; continue; }
  if (text !== before) fs.writeFileSync(p, text);
  total += n;
}

if (!CHECK) {
  const lines = [
    '# Clean URLs: every .html URL 301s to its extensionless form.',
    '# Generated by scripts/clean-urls.js. Re-run it after adding a page.',
    ...pages.map(f => {
      const slug = f.slice(0, -5);
      return `/${f}  ${clean(slug)}  301!`;
    }),
    '',
  ];
  fs.writeFileSync(path.join(root, '_redirects'), lines.join('\n'));
}

console.log(`${CHECK ? 'Remaining' : 'Rewrote'} ${total} URLs across ${targets.length} files; ${pages.length} redirect rules.`);
if (report.length) console.log(report.join('\n'));
